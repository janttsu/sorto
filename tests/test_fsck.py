class Reviewer:
    """Stands in for the structure model: canned answers per category, and for the whole tree."""

    model = "fake-35b"

    def __init__(self, categories=None, structure=None, fail=()):
        self.categories = categories or {}
        self.structure = structure or {"proposals": []}
        self.fail = set(fail)
        self.asked: list[str] = []

    def health(self):
        return True, "ok"

    def review_category(self, question: str) -> dict:
        self.asked.append(question)
        num = question.split("CATEGORY: ", 1)[1][:2]
        if num in self.fail:
            raise RuntimeError("model went away")
        return self.categories.get(num, {})

    def review_structure(self, question: str) -> dict:
        self.asked.append(question)
        return self.structure


