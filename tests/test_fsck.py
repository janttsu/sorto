def test_without_a_terminal_and_without_yes_nothing_is_written(tree: Path) -> None:
    before = {p: p.read_bytes() for p in tree.rglob("*.md")}
    out = io.StringIO()
    status = run(tree, llm=Reviewer(), out=out, interactive=False)
    assert status == EXIT_LEFT
    assert {p: p.read_bytes() for p in tree.rglob("*.md")} == before
    assert not (tree / LIFE / "14 Travel" / "14.00 JDex").exists()
    assert "none written: run in a terminal to accept them one by one, or with --yes" in out.getvalue()


def test_each_file_is_written_only_when_accepted(tree: Path) -> None:
    answers = iter(["y", "n", "q"])
    out = io.StringIO()
    status = run(tree, llm=Reviewer(), out=out, ask=lambda _prompt: next(answers), interactive=True)
    assert status == EXIT_FIXED | EXIT_LEFT
    health = (tree / HEALTH / "11.00 JDex" / "JDex.md").read_text(encoding="utf-8")
    money = (tree / MONEY / "13.00 JDex" / "JDex.md").read_text(encoding="utf-8")
    assert "Records" in health and "11.13` Dental" in health  # first: accepted
    assert money == MONEY_NOTE  # second: declined
    assert not (tree / LIFE / "14 Travel" / "14.00 JDex").exists()  # quit before the third
    (backup,) = (tree.parent / "sorto-home" / "fsck-backups").glob(f"*/{HEALTH}/11.00 JDex/JDex.md")
    assert backup.read_text(encoding="utf-8") == HEALTH_NOTE


def test_yes_writes_everything_and_a_second_run_finds_only_what_needs_a_human(tree: Path) -> None:
    assert run(tree, llm=Reviewer(), yes=True, out=io.StringIO()) == EXIT_FIXED | EXIT_LEFT  # the generated note is left
    assert (tree / LIFE / "14 Travel" / "14.01 Inbox").is_dir()
    report = check(tree)
    assert report.changes == []
    assert all("00.00 JDex.md" in p or "mentions IDs" in p for p in report.problems)
    (tree / "00-09 System/00 Admin/00.00 JDex/00.00 JDex.md").write_text("# 00.00 JDex — 00 Admin\n", encoding="utf-8")
    for note in tree.rglob("JDex.md"):  # drop the prose mentions too: then all agrees
        note.write_text("".join(ln for ln in note.read_text(encoding="utf-8").splitlines(keepends=True)
                                if "16.11" not in ln and "→" not in ln), encoding="utf-8")
    out = io.StringIO()
    assert run(tree, llm=Reviewer(), out=out, interactive=False) == EXIT_CLEAN
    assert "the structure and the JDex notes agree" in out.getvalue()


def test_a_note_changed_meanwhile_is_not_overwritten(tree: Path) -> None:
    note = tree / HEALTH / "11.00 JDex" / "JDex.md"

    def ask(_prompt: str) -> str:
        note.write_text(HEALTH_NOTE + "- 11.13 Dental\n", encoding="utf-8")  # the user edits it meanwhile
        return "y"

    out = io.StringIO()
    run(tree, llm=Reviewer(), out=out, ask=ask, interactive=True)
    assert note.read_text(encoding="utf-8").endswith("- 11.13 Dental\n")
    assert "changed on disk since it was checked" in out.getvalue()


