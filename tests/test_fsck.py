def _change(report, rel_end: str):
    return next(c for c in report.changes if c.rel.endswith(rel_end))


def test_table_entries_are_brought_in_line_and_everything_else_is_kept(tree: Path) -> None:
    report = check(tree)
    money = _change(report, "13.00 JDex/JDex.md")
    assert money.reasons == ["removed 13.14 Old savings: no such ID on disk", "added 13.13 Invoices"]
    lines = money.new.splitlines()
    assert "| 13.13 | Invoices | |" in lines  # in the table that has names, in number order, in its style
    assert lines.index("| 13.13 | Invoices | |") == lines.index("| 13.12 | Taxes | Returns and decisions |") + 1
    assert "13.14" not in money.new
    # Prose, the table of sources and the cross-reference stay exactly as they were.
    for kept in ("Bills go straight into the IDs. Moved here from 16.11 in the spring.",
                 "| 13.11 | `old-bank/`, `statements/` |", "- 13.15 Pension → now in 11.13"):
        assert kept in lines
    assert any("13.00 JDex/JDex.md: mentions IDs that are not on disk: 13.15, 16.11" in p for p in report.problems)


