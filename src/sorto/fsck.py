"""``sorto fsck``: check a Johnny.Decimal tree's structure and its JDex notes, and offer fixes.

The tree on disk is the truth; the notes are brought in line with it. Every
change to a file is shown first and written only when the user accepts it,
file by file (``--yes`` accepts all). Before a note is changed its previous
version is copied to sorto's own directory. Folders are never renamed or
moved: what is wrong in the structure itself is reported, not fixed.

What is proposed, per note:

- an entry for every ID of the note's own category that the notes of that
  category do not list (a note in ``31.00 JDex/`` is responsible for 31);
- an entry whose ID is not on disk is removed, or, when a folder with the
  same name exists under another number, changed to that number;
- an entry whose name differs from the folder's name gets the folder's name.

A category without a note gets one (and its ``NN.00`` / ``NN.01`` folders).
Prose that merely mentions an ID that is gone is history, not an entry: it is
reported and left alone. A note that says it is generated by something else
is not changed; what it lacks is reported, to be fixed in its generator.
"""

